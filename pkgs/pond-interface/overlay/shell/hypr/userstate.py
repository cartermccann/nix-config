#!/usr/bin/env python3
"""Pond's own Hyprland settings, kept as validated data.

The compositor configuration is generated by Nix and read-only. Changes made
in Pond's settings live in $XDG_STATE_HOME/pond-interface/hyprland.json, are
validated on every read and write, and are applied at runtime through
fixed Lua templates (hl.monitor / hl.config) after the declared config.
Removing a section and reloading Hyprland returns to the declared defaults.

  userstate.py restore          apply saved settings (Pond startup, config reload)
  userstate.py reset [display|input|all]
  userstate.py show
"""
import contextlib
import fcntl
import json
import math
import os
from pathlib import Path
import sys
import tempfile
import time

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ipc  # noqa: E402
import monitors  # noqa: E402
import xkb  # noqa: E402

VERSION = 1
INPUT_KEYS = {"kb_layout", "kb_variant", "sensitivity", "accel_profile", "scroll_factor",
              "natural_scroll", "touchpad_natural_scroll"}


class InvalidState(ValueError):
    pass


def state_dir():
    base = os.environ.get("XDG_STATE_HOME") or str(Path.home() / ".local/state")
    return Path(base) / "pond-interface"


def state_path():
    return state_dir() / "hyprland.json"


def pending_path():
    # Unconfirmed display changes belong to this login only.
    runtime = os.environ.get("XDG_RUNTIME_DIR") or str(state_dir())
    return Path(runtime) / "pond-display-pending.json"


@contextlib.contextmanager
def locked():
    state_dir().mkdir(parents=True, exist_ok=True)
    with (state_dir() / ".hyprland.lock").open("w") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False, prefix="." + path.name) as handle:
        temporary = Path(handle.name)
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    try:
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def validate_input(values):
    if not isinstance(values, dict) or set(values) - INPUT_KEYS:
        raise InvalidState("Unknown input setting")
    if "kb_layout" in values:
        layout = values["kb_layout"]
        variant = values.get("kb_variant", "")
        if not isinstance(layout, str) or not isinstance(variant, str):
            raise InvalidState("Keyboard layouts are invalid")
        ids = xkb.identifiers(layout, variant)
        if not 1 <= len(ids) <= 8 or len(ids) != len([p for p in layout.split(",")]):
            raise InvalidState("Keyboard layouts are invalid")
        catalog = xkb.layouts()
        if any(identifier not in catalog for identifier in ids):
            raise InvalidState("Unknown keyboard layout")
    elif "kb_variant" in values:
        raise InvalidState("A keyboard variant needs a layout")
    if "sensitivity" in values:
        value = values["sensitivity"]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not -1 <= value <= 1:
            raise InvalidState("Pointer speed is invalid")
    if "scroll_factor" in values:
        value = values["scroll_factor"]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not 0.1 <= value <= 2:
            raise InvalidState("Scroll speed is invalid")
    if "accel_profile" in values and values["accel_profile"] not in ("adaptive", "flat"):
        raise InvalidState("Pointer acceleration is invalid")
    for key in ("natural_scroll", "touchpad_natural_scroll"):
        if key in values and type(values[key]) is not bool:
            raise InvalidState("Natural scrolling is invalid")
    return values


def validate(state):
    if not isinstance(state, dict) or state.get("version") != VERSION or set(state) - {"version", "monitors", "input"}:
        raise InvalidState("Unsupported settings file")
    displays = state.get("monitors", {})
    if not isinstance(displays, dict) or len(displays) > 16:
        raise InvalidState("Display settings are invalid")
    for name, entry in displays.items():
        try:
            ipc.output_name(name)
            monitors.validate(entry)
        except ValueError as error:
            raise InvalidState(f"{name}: {error}") from error
    validate_input(state.get("input", {}))
    return state


def empty():
    return {"version": VERSION, "monitors": {}, "input": {}}


def load():
    try:
        text = state_path().read_text()
    except FileNotFoundError:
        return empty()
    try:
        state = json.loads(text)
    except ValueError as error:
        raise InvalidState("Pond's settings file is not valid JSON; reset it in Settings") from error
    state = validate(state)
    state.setdefault("monitors", {})
    state.setdefault("input", {})
    return state


def save(state):
    validate(state)
    atomic_write(state_path(), json.dumps(state, indent=2, sort_keys=True) + "\n")


def input_lua(values):
    validate_input(values)
    options = {}
    for key in ("kb_layout", "kb_variant", "sensitivity", "accel_profile", "scroll_factor", "natural_scroll"):
        if key in values:
            options[key] = values[key]
    if "kb_layout" in values:
        options.setdefault("kb_variant", "")
    if "touchpad_natural_scroll" in values:
        options["touchpad"] = {"natural_scroll": values["touchpad_natural_scroll"]}
    return f"hl.config({{ input = {ipc.lua_value(options)} }})" if options else ""


PHASES = ("applying", "applied", "failed")


def validate_pending(record):
    """An unconfirmed display transaction: the rollback point is `before`."""
    if not isinstance(record, dict) or set(record) - {"id", "phase", "deadline", "before", "after", "error"}:
        raise InvalidState("Unknown display transaction")
    if not isinstance(record.get("id"), str) or not 0 < len(record["id"]) <= 64 or not record["id"].isalnum():
        raise InvalidState("Display transaction ID is invalid")
    if record.get("phase") not in PHASES:
        raise InvalidState("Display transaction phase is invalid")
    deadline = record.get("deadline")
    if isinstance(deadline, bool) or not isinstance(deadline, (int, float)) or not math.isfinite(deadline):
        raise InvalidState("Display transaction deadline is invalid")
    for key in ("before", "after"):
        entries = record.get(key)
        if not isinstance(entries, dict) or not entries or len(entries) > 16:
            raise InvalidState("Display transaction is incomplete")
        for name, entry in entries.items():
            try:
                ipc.output_name(name)
                monitors.validate(entry)
            except ValueError as error:
                raise InvalidState(f"{name}: {error}") from error
    if not isinstance(record.get("error", ""), str):
        raise InvalidState("Display transaction error is invalid")
    return record


def read_pending():
    """The unconfirmed display transaction, or None. A record that exists but
    cannot be read raises: its rollback point must not be silently lost."""
    try:
        text = pending_path().read_text()
    except FileNotFoundError:
        return None
    try:
        return validate_pending(json.loads(text))
    except ValueError as error:
        raise InvalidState(f"The unconfirmed display change cannot be read: {error}") from error


def write_pending(record):
    atomic_write(pending_path(), json.dumps(validate_pending(record)) + "\n")


def revert_pending(pending, run_lua=ipc.run_lua, query=ipc.query):
    """Restore a transaction's previous settings, verified, and only then
    retire it. On failure the record stays (marked failed) for a retry."""
    try:
        left = monitors.restore_previous(pending["before"], run_lua=run_lua, query=query)
    except (ipc.HyprError, monitors.DisplayError, ValueError) as error:
        # Due again shortly, so the watchdog (or a stale status check)
        # retries instead of waiting out a confirmation period.
        with contextlib.suppress(OSError, InvalidState):
            write_pending(dict(pending, phase="failed", error=str(error),
                               deadline=min(pending["deadline"], time.time() + 2)))
        raise monitors.DisplayError(f"Could not restore the previous display settings: {error}") from error
    pending_path().unlink(missing_ok=True)
    return left


def restore(run_lua=ipc.run_lua, query=ipc.query, now=time.time):
    """Apply saved settings to the live session; never raises for one bad monitor."""
    report = {"applied": [], "skipped": [], "errors": []}
    with locked():
        # A reload or shell restart ends any unconfirmed display change: its
        # confirmation dialog is gone. Hyprland keeps the changed layout on a
        # shell restart, so restore the transaction's previous settings and
        # verify them before retiring it; displays it could not restore keep
        # the record (and their saved settings are not layered on top).
        blocked = set()
        try:
            pending = read_pending()
        except InvalidState as error:
            report["errors"].append(str(error))
            pending = None
        if pending is not None:
            try:
                left = revert_pending(pending, run_lua=run_lua, query=query)
                report["skipped"].append("unconfirmed display change (reverted)")
                report["skipped"] += [f"{name}: unconfirmed change not reverted (disconnected)" for name in left]
            except monitors.DisplayError as error:
                report["errors"].append(f"unconfirmed display change: {error}")
                blocked = set(pending["before"])
        try:
            state = load()
        except InvalidState as error:
            report["errors"].append(str(error))
            return report
        if state["input"]:
            try:
                run_lua(input_lua(state["input"]))
                report["applied"].append("input")
            except (ipc.HyprError, ValueError) as error:
                report["errors"].append(f"input: {error}")
        try:
            live = monitors.active(query)
        except ipc.HyprError as error:
            report["errors"].append(str(error))
            return report
        wanted = {}
        for name, settings in state["monitors"].items():
            m = live.get(name)
            if name in blocked:
                report["skipped"].append(f"{name}: unconfirmed change still pending")
            elif m is None:
                report["skipped"].append(f"{name}: not connected")
            elif monitors.identity(m) != settings["identity"]:
                report["skipped"].append(f"{name}: a different display is connected")
            elif not any(mode["id"] == settings["mode"] for mode in monitors.modes(m)):
                report["skipped"].append(f"{name}: mode {settings['mode']} is not offered")
            else:
                wanted[name] = settings
        # Positions only make sense as a whole layout; keep the declared
        # positions when the saved arrangement no longer fits together.
        layout = {name: wanted.get(name) or monitors.live_settings(m) for name, m in live.items()}
        try:
            validate_layout([monitors.rect(name, s) for name, s in layout.items()])
        except ValueError:
            for name in wanted:
                wanted[name] = dict(wanted[name], position=monitors.live_settings(live[name])["position"])
            if wanted:
                report["skipped"].append("saved arrangement (displays changed)")
        if wanted:
            try:
                monitors.apply(wanted, run_lua=run_lua, query=query)
                report["applied"] += sorted(wanted)
            except (ipc.HyprError, monitors.DisplayError, ValueError) as error:
                report["errors"].append(f"displays: {error}")
    return report


def reset(section="all", request=ipc.request, run_lua=ipc.run_lua, query=ipc.query):
    if section not in ("display", "input", "all"):
        raise ValueError("Unknown settings section")
    with locked():
        try:
            state = load()
        except InvalidState:
            state = empty()
        if section in ("display", "all"):
            state["monitors"] = {}
        if section in ("input", "all"):
            state["input"] = {}
        save(state)
        # Reloading re-reads the declared configuration, which also replaces
        # any unconfirmed display change; only then is its record obsolete.
        reply = request("reload").strip()
        if reply != "ok":
            raise ipc.HyprError(reply or "Hyprland did not reload")
        pending_path().unlink(missing_ok=True)
    # Pond reapplies whatever remains saved.
    return restore(run_lua=run_lua, query=query)


# --- Layout rules shared with the display settings ---------------------------

def overlaps(a, b):
    return (a["x"] < b["x"] + b["width"] and b["x"] < a["x"] + a["width"]
            and a["y"] < b["y"] + b["height"] and b["y"] < a["y"] + a["height"])


def adjacent(a, b):
    return (((a["x"] + a["width"] == b["x"] or b["x"] + b["width"] == a["x"])
             and min(a["y"] + a["height"], b["y"] + b["height"]) > max(a["y"], b["y"]))
            or ((a["y"] + a["height"] == b["y"] or b["y"] + b["height"] == a["y"])
                and min(a["x"] + a["width"], b["x"] + b["width"]) > max(a["x"], b["x"])))


def validate_layout(rects):
    if not rects:
        raise ValueError("No connected displays")
    for i, a in enumerate(rects):
        for k in ("x", "y", "width", "height"):
            if type(a[k]) is not int or abs(a[k]) > 1000000:
                raise ValueError("Invalid display coordinates")
        if a["width"] <= 0 or a["height"] <= 0:
            raise ValueError("Invalid display size")
        if any(overlaps(a, b) for b in rects[i + 1:]):
            raise ValueError("Displays cannot overlap")
    reached = {0}
    while True:
        more = {i for i, a in enumerate(rects) if any(adjacent(a, rects[j]) for j in reached)} - reached
        if not more:
            break
        reached |= more
    if len(reached) != len(rects):
        raise ValueError("Display edges must touch so the cursor can move between them")


def main():
    action, *args = sys.argv[1:] or ["show"]
    try:
        if action == "restore":
            result = restore()
        elif action == "reset":
            result = reset(*(args or ["all"]))
        elif action == "show":
            result = load()
        else:
            raise ValueError("Unknown action")
    except (InvalidState, ValueError, ipc.HyprError, OSError) as error:
        print(json.dumps({"error": str(error)}))
        sys.exit(1)
    print(json.dumps(result))
    if isinstance(result, dict) and result.get("errors"):
        sys.exit(2)


if __name__ == "__main__":
    main()
